// Generate THIRD_PARTY_NOTICES.md for the Windows installer (task QA-04).
//
// Covers everything that ends up in the shipped program:
//  - Rust crates linked into senvakara (the Slint app) for x86_64-pc-windows-msvc
//    (normal dependencies only; build/dev dependencies are not shipped),
//  - the scrcpy-server binary embedded in the executable,
//  - the Slint attribution required by its royalty-free licence.
// Icons in apps/senvakara/ui/icons are the project's own drawings; no font is bundled.
// License texts are copied from each package's own LICENSE/COPYING/NOTICE
// files and de-duplicated; packages without such files are listed.
//
// Usage (repo root):  node tools/licenses/gen-notices.mjs
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "../..");
const out = path.join(root, "apps/senvakara/resources/THIRD_PARTY_NOTICES.md");
const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense)([-._].*)?$/i;

const run = (cmd, args, cwd = root) => execFileSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
const licenseFiles = (dir) =>
  fs
    .readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f) && fs.statSync(path.join(dir, f)).isFile())
    .sort();

// ---------- Rust ----------
const tree = run("cargo", [
  "tree", "-p", "senvakara", "-e", "normal", "--target", "x86_64-pc-windows-msvc", "--prefix", "none", "-f", "{p}",
]);
const wanted = new Set(
  tree
    .split(/\r?\n/)
    .map((l) => l.trim().match(/^(\S+) v(\S+)/))
    .filter(Boolean)
    .map((m) => `${m[1]}@${m[2]}`),
);
const meta = JSON.parse(run("cargo", ["metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"]));
const rust = meta.packages
  .filter((p) => wanted.has(`${p.name}@${p.version}`) && !p.name.startsWith("senvakara-"))
  .map((p) => ({
    eco: "Rust crate",
    name: p.name,
    version: p.version,
    license: p.license ?? p.license_file ?? "unknown",
    repo: p.repository ?? "",
    authors: p.authors ?? [],
    dir: path.dirname(p.manifest_path),
  }));

// ---------- texts ----------
const all = [...rust].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const texts = new Map(); // hash -> { text, users: [] }
const missing = [];
for (const pkg of all) {
  const files = licenseFiles(pkg.dir);
  pkg.texts = [];
  if (files.length === 0) missing.push(pkg);
  for (const f of files) {
    const text = fs.readFileSync(path.join(pkg.dir, f), "utf8").replace(/\r\n/g, "\n").trim();
    const h = createHash("sha256").update(text).digest("hex").slice(0, 12);
    if (!texts.has(h)) texts.set(h, { text, users: [] });
    texts.get(h).users.push(`${pkg.name} ${pkg.version} (${f})`);
    pkg.texts.push(h);
  }
}

// scrcpy-server is Apache-2.0; take the canonical Apache text from a crate that ships it.
const apache = [...texts.entries()].find(([, t]) => /Apache License\s+Version 2\.0, January 2004/.test(t.text) && /END OF TERMS AND CONDITIONS/.test(t.text));
if (!apache) throw new Error("no full Apache-2.0 text found among dependencies");
apache[1].users.push("scrcpy-server 3.3.3 (embedded in the executable)");

const lines = [];
lines.push("# Third-party components in Senvakara", "");
lines.push("Generated by `tools/licenses/gen-notices.mjs`. Senvakara itself is not covered by this file.", "");
lines.push("## User interface toolkit", "");
lines.push("Senvakara's interface is made with [Slint](https://slint.dev), used under the Slint Royalty-free License 2.0. The attribution is also shown in Settings > About.", "");
lines.push("## Bundled binary", "");
lines.push("### scrcpy-server v3.3.3", "");
lines.push("- File: `scrcpy-server-v3.3.3`, embedded in `senvakara.exe` and pushed to an Android device at run time for screen mirroring");
lines.push("- Source: https://github.com/Genymobile/scrcpy (release v3.3.3), unmodified");
lines.push("- SHA-256: `7e70323ba7f259649dd4acce97ac4fefbae8102b2c6d91e2e7be613fd5354be0` (verified before every push)");
lines.push("- Copyright (C) 2018 Genymobile; Copyright (C) 2018-2025 Romain Vimont");
lines.push(`- License: Apache License 2.0 — full text below as [${apache[0]}](#text-${apache[0]})`, "");
lines.push("## Mozilla Public License 2.0 components", "");
lines.push("The following MPL-2.0 components are used unmodified. Their source code is available from the listed repositories (and, for Rust crates, from https://crates.io).", "");
for (const p of all.filter((p) => /MPL/.test(p.license))) lines.push(`- ${p.name} ${p.version} — ${p.repo || "see package registry"}`);
lines.push("");
lines.push(`## Components (${all.length})`, "");
lines.push("| Component | Version | Kind | License | License texts |", "|---|---|---|---|---|");
for (const p of all) lines.push(`| ${p.name} | ${p.version} | ${p.eco} | ${p.license.replace(/\|/g, "/")} | ${p.texts.map((h) => `[${h}](#text-${h})`).join(" ") || "—"} |`);
lines.push("");
if (missing.length) {
  lines.push("## Components whose package ships no license file", "");
  lines.push("These are covered by the license named in their package metadata, with copyright held by the listed authors. The standard text of each of these licenses appears below where another component ships it.", "");
  for (const p of missing)
    lines.push(`- ${p.name} ${p.version} — ${p.license} — Copyright (c) ${p.authors.length ? p.authors.map((a) => a.replace(/\s*<.*$/, "")).join(", ") : "the authors"}${p.repo ? ` — ${p.repo}` : ""}`);
  lines.push("");
}
lines.push("## License texts", "");
for (const [h, t] of texts) {
  lines.push(`<a id="text-${h}"></a>`, `### ${h}`, "", `Used by: ${t.users.join(", ")}`, "", "```text", t.text, "```", "");
}
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${path.relative(root, out)}: ${all.length} Rust crates, ${texts.size} distinct texts, ${missing.length} without license file, ${(fs.statSync(out).size / 1024).toFixed(0)} KiB`);
const spdx = new Map();
for (const p of all) spdx.set(p.license, (spdx.get(p.license) ?? 0) + 1);
const copyleft = all.filter((p) => /\b(GPL|LGPL|AGPL|SSPL|EUPL|CDDL)/i.test(p.license));
console.log(`strong/weak copyleft besides MPL: ${copyleft.map((p) => p.name + " " + p.license).join(", ") || "none"}`);
if (missing.length) console.log("no license file: " + missing.map((p) => `${p.name}@${p.version} [${p.license}]`).join(", "));
